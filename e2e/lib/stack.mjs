// Starts and stops everything the end-to-end suites need: fake Supabase projects, fake Gemini and
// Cal.com, and the real Worker in `wrangler dev`. Everything it creates lives under e2e/.work
// (ignored by git), and the Worker's local data never touches your own .wrangler/state.
import { spawn } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const ROOT = path.resolve(fileURLToPath(new URL('../..', import.meta.url)));
export const E2E = path.join(ROOT, 'e2e');
export const WORK = path.join(E2E, '.work');
export const SHOTS = path.join(WORK, 'shots');
export const STATE = path.join(WORK, 'state');
export const BASE = 'http://127.0.0.1:8799';
const PIDS = path.join(WORK, 'pids.json');
const DEV_VARS = path.join(ROOT, '.dev.vars');
const SMOKE_CONFIG = path.join(ROOT, '.smoke.wrangler.json');
const MARKER = '# metisai-e2e: generated by e2e/lib/stack.mjs, safe to delete';

export const PASSCODE = 'e2e-passcode-123';
export const DATABASES = [
  { port: 9921, key: 'sb_secret_e2e_clinic_one_key_000000001', flag: '' },
  { port: 9922, key: 'sb_secret_e2e_clinic_two_key_000000002', flag: '' },
  { port: 9923, key: 'sb_secret_e2e_clinic_three_key_0000003', flag: '--no-tables' },
  { port: 9924, key: 'sb_secret_e2e_legacy_clinic_key_0000004', flag: '--legacy' },
];
export const DEFAULT_ENCRYPTION_KEY = 'cd'.repeat(32);

const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));
const env = { ...process.env, NO_PROXY: '127.0.0.1,localhost', no_proxy: '127.0.0.1,localhost' };

function readPids() {
  try { return JSON.parse(fs.readFileSync(PIDS, 'utf8')); } catch { return {}; }
}
function writePids(pids) {
  fs.mkdirSync(WORK, { recursive: true });
  fs.writeFileSync(PIDS, JSON.stringify(pids));
}

/** Remove // and /* *\/ comments and trailing commas without touching strings. */
export function stripJsonComments(text) {
  let out = '';
  let inString = false;
  for (let i = 0; i < text.length; i += 1) {
    const c = text[i];
    const next = text[i + 1];
    if (inString) {
      out += c;
      if (c === '\\') { out += next; i += 1; } else if (c === '"') inString = false;
    } else if (c === '"') { inString = true; out += c; }
    else if (c === '/' && next === '/') { while (i < text.length && text[i] !== '\n') i += 1; }
    else if (c === '/' && next === '*') { i += 2; while (!(text[i] === '*' && text[i + 1] === '/')) i += 1; i += 1; }
    else out += c;
  }
  return out.replace(/,(\s*[}\]])/g, '$1');
}

/** Write the local-only Worker config and variables. Refuses to replace a .dev.vars that is not ours. */
export function writeConfig({ encryptionKey = DEFAULT_ENCRYPTION_KEY } = {}) {
  if (fs.existsSync(DEV_VARS) && !fs.readFileSync(DEV_VARS, 'utf8').startsWith(MARKER)) {
    throw new Error('A .dev.vars file of yours exists in the repository root. Move it aside while running the e2e suites (they write their own and delete it afterwards).');
  }
  const config = JSON.parse(stripJsonComments(fs.readFileSync(path.join(ROOT, 'wrangler.jsonc'), 'utf8')));
  config.vars = { ...(config.vars ?? {}), NODE_ENV: 'development' };
  fs.writeFileSync(SMOKE_CONFIG, JSON.stringify(config, null, 2));
  fs.writeFileSync(DEV_VARS, [
    MARKER,
    `DASHBOARD_ADMIN_PASSCODE=${PASSCODE}`,
    `DASHBOARD_SESSION_SECRET=${'ab'.repeat(32)}`,
    `TENANT_CREDENTIALS_ENCRYPTION_KEY=${encryptionKey}`,
    `APP_PUBLIC_URL=${BASE}`,
    'GEMINI_LIVE_ORIGIN=http://127.0.0.1:9912',
    'CALCOM_API_URL=http://127.0.0.1:9913/v2',
    '',
  ].join('\n'));
}

export function removeConfig() {
  try { if (fs.readFileSync(DEV_VARS, 'utf8').startsWith(MARKER)) fs.rmSync(DEV_VARS); } catch { /* not there */ }
  fs.rmSync(SMOKE_CONFIG, { force: true });
}

function launch(name, command, args, cwd) {
  fs.mkdirSync(WORK, { recursive: true });
  const log = fs.openSync(path.join(WORK, `${name}.log`), 'w');
  // A process group of its own, so stopping it also stops everything it started (workerd, for one).
  const child = spawn(command, args, { cwd, env, detached: true, stdio: ['ignore', log, log] });
  child.unref();
  const pids = readPids();
  pids[name] = child.pid;
  writePids(pids);
  return child.pid;
}

function killGroup(pid) {
  for (const target of [-pid, pid]) { try { process.kill(target, 'SIGKILL'); } catch { /* already gone */ } }
}

async function waitFor(check, what, seconds) {
  for (let i = 0; i < seconds * 2; i += 1) {
    try { if (await check()) return; } catch { /* not yet */ }
    await sleep(500);
  }
  throw new Error(`Timed out waiting for ${what}. See the logs in ${WORK}.`);
}

const up = (url) => async () => (await fetch(url)).status < 500;
const down = (port) => async () => { try { await fetch(`http://127.0.0.1:${port}/`); return false; } catch { return true; } };

export async function startFakes() {
  for (const { port, key, flag } of DATABASES) {
    launch(`db-${port}`, process.execPath, [path.join(E2E, 'fakes', 'supabase.mjs'), String(port), key, ...(flag ? [flag] : [])], E2E);
  }
  launch('gemini-and-calcom', process.execPath, [path.join(E2E, 'fakes', 'gemini-and-calcom.mjs')], E2E);
  for (const { port } of DATABASES) await waitFor(up(`http://127.0.0.1:${port}/__dump`), `the fake database on ${port}`, 20);
  await waitFor(up('http://127.0.0.1:9912/__state'), 'the fake Gemini and Cal.com', 20);
}

export async function stopFakes() {
  const pids = readPids();
  for (const name of Object.keys(pids)) if (name !== 'worker') { killGroup(pids[name]); delete pids[name]; }
  writePids({ worker: pids.worker });
}

export async function startWorker({ wipe = false } = {}) {
  if (wipe) fs.rmSync(STATE, { recursive: true, force: true });
  if (!fs.existsSync(path.join(ROOT, 'dist', 'client', 'index.html'))) throw new Error('Run `pnpm build` first: the Worker serves the built dashboard from dist/client.');
  const pid = launch('worker', 'npx', ['wrangler', 'dev', '--config', '.smoke.wrangler.json', '--port', '8799', '--persist-to', STATE], ROOT);
  void pid;
  await waitFor(up(`${BASE}/api/session`), 'the Worker to start', 120);
}

export async function stopWorker() {
  const pids = readPids();
  if (pids.worker) killGroup(pids.worker);
  delete pids.worker;
  writePids(pids);
  await waitFor(down(8799), 'the Worker to stop', 20);
}

/** Everything fresh: fake services started, Worker started, saved data wiped unless told otherwise. */
export async function startAll({ wipe = true, encryptionKey } = {}) {
  await stopAll();
  writeConfig({ encryptionKey });
  await startFakes();
  await startWorker({ wipe });
}

export async function stopAll() {
  await stopWorker();
  await stopFakes();
}
